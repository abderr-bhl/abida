'use client';

import { useState, useCallback } from 'react';
import { Task } from '@/types';
import {
  CheckCircle,
  Circle,
  XCircle,
  ExternalLink,
  RefreshCcw,
  Clock
} from 'lucide-react';

export default function AdminTasksPage() {
  const [tasks, setTasks] = useState<Task[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [token, setToken] = useState<string>('');
  const [isAuthenticated, setIsAuthenticated] = useState(false);

  const fetchTasks = useCallback(async (authToken: string) => {
    setLoading(true);
    try {
      const response = await fetch('/api/admin/tasks', {
        headers: {
          'Authorization': `Bearer ${authToken}`
        }
      });

      if (response.ok) {
        const data = await response.json();
        setTasks(data);
        setIsAuthenticated(true);
        setError(null);
      } else {
        if (response.status === 401) {
          setError('Invalid token');
          setIsAuthenticated(false);
        } else {
          setError('Failed to fetch tasks');
        }
      }
    } catch {
      setError('An error occurred while fetching tasks');
    } finally {
      setLoading(false);
    }
  }, []);

  const handleLogin = (e: React.FormEvent) => {
    e.preventDefault();
    fetchTasks(token);
  };

  const updateTaskStatus = async (id: string, status: Task['status']) => {
    try {
      const response = await fetch('/api/admin/tasks', {
        method: 'PATCH',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${token}`
        },
        body: JSON.stringify({ id, status })
      });

      if (response.ok) {
        setTasks(prev => prev.map(t => t.id === id ? { ...t, status } : t));
      } else {
        alert('Failed to update task');
      }
    } catch {
      alert('Error updating task');
    }
  };

  if (!isAuthenticated) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-gray-50 dark:bg-gray-900 px-4">
        <div className="max-w-md w-full space-y-8 p-8 bg-white dark:bg-gray-800 rounded-xl shadow-lg">
          <div className="text-center">
            <h2 className="text-3xl font-extrabold text-gray-900 dark:text-white">Admin Access</h2>
            <p className="mt-2 text-sm text-gray-600 dark:text-gray-400">Enter your token to manage tasks</p>
          </div>
          <form className="mt-8 space-y-6" onSubmit={handleLogin}>
            <input
              type="password"
              required
              className="appearance-none rounded-md relative block w-full px-3 py-2 border border-gray-300 placeholder-gray-500 text-gray-900 focus:outline-none focus:ring-primary focus:border-primary focus:z-10 sm:text-sm dark:bg-gray-700 dark:border-gray-600 dark:text-white"
              placeholder="Admin Token"
              value={token}
              onChange={(e) => setToken(e.target.value)}
            />
            <button
              type="submit"
              className="group relative w-full flex justify-center py-2 px-4 border border-transparent text-sm font-medium rounded-md text-white bg-primary hover:bg-blue-700 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-primary"
            >
              Access Dashboard
            </button>
            {error && <p className="text-red-500 text-center text-sm">{error}</p>}
          </form>
        </div>
      </div>
    );
  }

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-12">
      <div className="flex justify-between items-center mb-8">
        <div>
          <h1 className="text-3xl font-bold text-gray-900 dark:text-white flex items-center gap-2">
            Automated Tasks Dashboard
          </h1>
          <p className="text-gray-600 dark:text-gray-400">Manage tasks generated by competitor benchmarking</p>
        </div>
        <button
          onClick={() => fetchTasks(token)}
          className="flex items-center gap-2 px-4 py-2 bg-gray-100 hover:bg-gray-200 dark:bg-gray-800 dark:hover:bg-gray-700 rounded-md transition-colors"
        >
          <RefreshCcw size={18} className={loading ? 'animate-spin' : ''} />
          Refresh
        </button>
      </div>

      {loading && tasks.length === 0 ? (
        <div className="flex justify-center py-12">
          <RefreshCcw className="animate-spin text-primary" size={48} />
        </div>
      ) : tasks.length === 0 ? (
        <div className="bg-white dark:bg-gray-800 rounded-lg p-12 text-center border-2 border-dashed border-gray-200 dark:border-gray-700">
          <Clock className="mx-auto text-gray-400 mb-4" size={48} />
          <h3 className="text-lg font-medium text-gray-900 dark:text-white">No tasks found</h3>
          <p className="text-gray-500">Wait for the next automated benchmark or check back later.</p>
        </div>
      ) : (
        <div className="bg-white dark:bg-gray-800 shadow overflow-hidden sm:rounded-md border border-gray-200 dark:border-gray-700">
          <ul className="divide-y divide-gray-200 dark:divide-gray-700">
            {tasks.map((task) => (
              <li key={task.id}>
                <div className="px-4 py-4 sm:px-6 hover:bg-gray-50 dark:hover:bg-gray-700/50 transition-colors">
                  <div className="flex items-center justify-between">
                    <div className="flex items-center gap-3">
                      <div className={`p-2 rounded-full ${
                        task.status === 'completed' ? 'bg-green-100 text-green-600' :
                        task.status === 'ignored' ? 'bg-gray-100 text-gray-600' :
                        'bg-blue-100 text-blue-600'
                      }`}>
                        {task.status === 'completed' ? <CheckCircle size={20} /> :
                         task.status === 'ignored' ? <XCircle size={20} /> :
                         <Circle size={20} />}
                      </div>
                      <p className="text-sm font-medium text-primary truncate">{task.competitor}</p>
                    </div>
                    <div className="ml-2 flex-shrink-0 flex gap-2">
                      <button
                        onClick={() => updateTaskStatus(task.id, 'completed')}
                        className={`p-1 rounded-md hover:bg-green-50 text-green-600 transition-colors ${task.status === 'completed' ? 'opacity-50 cursor-not-allowed' : ''}`}
                        title="Mark as completed"
                        disabled={task.status === 'completed'}
                      >
                        <CheckCircle size={20} />
                      </button>
                      <button
                        onClick={() => updateTaskStatus(task.id, 'ignored')}
                        className={`p-1 rounded-md hover:bg-red-50 text-red-600 transition-colors ${task.status === 'ignored' ? 'opacity-50 cursor-not-allowed' : ''}`}
                        title="Ignore task"
                        disabled={task.status === 'ignored'}
                      >
                        <XCircle size={20} />
                      </button>
                    </div>
                  </div>
                  <div className="mt-2 sm:flex sm:justify-between">
                    <div className="sm:flex flex-col">
                      <p className="text-lg font-semibold text-gray-900 dark:text-white">{task.title}</p>
                      <p className="mt-1 text-sm text-gray-600 dark:text-gray-400">{task.description}</p>
                      <div className="mt-2 flex items-center gap-4">
                        <a
                          href={task.sourceUrl}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="inline-flex items-center text-xs font-medium text-blue-600 hover:underline gap-1"
                          aria-label={`View source article for ${task.title} (opens in a new tab)`}
                        >
                          View Source <ExternalLink size={12} />
                        </a>
                        <span className="text-xs text-gray-400 flex items-center gap-1">
                          <Clock size={12} /> {new Date(task.createdAt).toLocaleDateString()}
                        </span>
                      </div>
                    </div>
                  </div>
                </div>
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}
