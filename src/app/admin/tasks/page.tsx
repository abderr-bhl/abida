import { getTasks } from '@/lib/automation/benchmark';
import { triggerBenchmark, updateTaskStatus, logoutAction } from './actions';

export const revalidate = 0;

export default async function AdminTasksPage() {
  const tasks = getTasks();

  const pendingTasks = tasks.filter(t => t.status === 'pending');
  const completedTasks = tasks.filter(t => t.status === 'completed');

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10">
      <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4 mb-8">
        <div>
          <h1 className="text-3xl font-extrabold text-gray-900 dark:text-white">
            Competitive Content Backlog
          </h1>
          <p className="text-gray-500 dark:text-gray-400 mt-1">
            Automated tasks generated by daily competitor RSS benchmark feeds (Wirecutter, RTINGS).
          </p>
        </div>

        <div className="flex items-center space-x-4">
          <form action={triggerBenchmark}>
            <button
              type="submit"
              className="bg-primary hover:bg-blue-700 text-white font-medium px-4 py-2 rounded-lg text-sm shadow transition-colors flex items-center space-x-2"
            >
              <span>Run Benchmark Now</span>
            </button>
          </form>

          <form action={logoutAction}>
            <button
              type="submit"
              className="bg-gray-200 dark:bg-gray-700 hover:bg-gray-300 dark:hover:bg-gray-600 text-gray-800 dark:text-white font-medium px-4 py-2 rounded-lg text-sm transition-colors"
            >
              Logout
            </button>
          </form>
        </div>
      </div>

      <div className="grid grid-cols-1 sm:grid-cols-3 gap-6 mb-8">
        <div className="bg-white dark:bg-gray-800 p-6 rounded-xl border border-gray-200 dark:border-gray-700 shadow-sm">
          <div className="text-sm font-medium text-gray-500 dark:text-gray-400">Pending Tasks</div>
          <div className="text-3xl font-bold text-gray-900 dark:text-white mt-2">{pendingTasks.length}</div>
        </div>
        <div className="bg-white dark:bg-gray-800 p-6 rounded-xl border border-gray-200 dark:border-gray-700 shadow-sm">
          <div className="text-sm font-medium text-gray-500 dark:text-gray-400">Completed Tasks</div>
          <div className="text-3xl font-bold text-gray-900 dark:text-white mt-2">{completedTasks.length}</div>
        </div>
        <div className="bg-white dark:bg-gray-800 p-6 rounded-xl border border-gray-200 dark:border-gray-700 shadow-sm">
          <div className="text-sm font-medium text-gray-500 dark:text-gray-400">Total Tracked</div>
          <div className="text-3xl font-bold text-gray-900 dark:text-white mt-2">{tasks.length}</div>
        </div>
      </div>

      <div className="bg-white dark:bg-gray-800 rounded-xl border border-gray-200 dark:border-gray-700 shadow-sm overflow-hidden">
        <div className="px-6 py-4 border-b border-gray-200 dark:border-gray-700 font-bold text-gray-900 dark:text-white">
          Tasks List
        </div>

        {tasks.length === 0 ? (
          <div className="p-12 text-center text-gray-500 dark:text-gray-400">
            No competitive benchmark tasks found yet. Click &quot;Run Benchmark Now&quot; to fetch latest competitor articles.
          </div>
        ) : (
          <div className="divide-y divide-gray-200 dark:divide-gray-700">
            {tasks.map((task) => (
              <div key={task.id} className="p-6 flex flex-col md:flex-row justify-between items-start md:items-center gap-4">
                <div className="space-y-1 max-w-2xl">
                  <div className="flex items-center space-x-2">
                    <span className="text-xs font-semibold px-2.5 py-0.5 rounded-full bg-blue-100 text-blue-800 dark:bg-blue-900/40 dark:text-blue-300">
                      {task.competitor}
                    </span>
                    <span className="text-xs font-semibold px-2.5 py-0.5 rounded-full bg-gray-100 text-gray-800 dark:bg-gray-700 dark:text-gray-300 capitalize">
                      {task.contentType}
                    </span>
                    <span className={`text-xs font-semibold px-2.5 py-0.5 rounded-full ${
                      task.status === 'completed'
                        ? 'bg-green-100 text-green-800 dark:bg-green-900/40 dark:text-green-300'
                        : task.status === 'pending'
                        ? 'bg-yellow-100 text-yellow-800 dark:bg-yellow-900/40 dark:text-yellow-300'
                        : 'bg-gray-100 text-gray-800 dark:bg-gray-700 dark:text-gray-300'
                    }`}>
                      {task.status}
                    </span>
                  </div>

                  <h3 className="text-lg font-bold text-gray-900 dark:text-white">
                    {task.title}
                  </h3>
                  <p className="text-sm text-gray-600 dark:text-gray-300">
                    {task.description}
                  </p>
                  <div className="text-xs text-gray-400 mt-2">
                    Source: <a href={task.sourceUrl} target="_blank" rel="noopener noreferrer" className="text-primary hover:underline">{task.sourceUrl}</a>
                  </div>
                </div>

                <div className="flex items-center space-x-2">
                  {task.status !== 'completed' && (
                    <form action={updateTaskStatus.bind(null, task.id, 'completed')}>
                      <button
                        type="submit"
                        className="px-3 py-1.5 text-xs font-medium bg-green-600 hover:bg-green-700 text-white rounded shadow-sm transition-colors"
                      >
                        Mark Completed
                      </button>
                    </form>
                  )}
                  {task.status !== 'pending' && (
                    <form action={updateTaskStatus.bind(null, task.id, 'pending')}>
                      <button
                        type="submit"
                        className="px-3 py-1.5 text-xs font-medium bg-yellow-600 hover:bg-yellow-700 text-white rounded shadow-sm transition-colors"
                      >
                        Mark Pending
                      </button>
                    </form>
                  )}
                  {task.status !== 'dismissed' && (
                    <form action={updateTaskStatus.bind(null, task.id, 'dismissed')}>
                      <button
                        type="submit"
                        className="px-3 py-1.5 text-xs font-medium bg-gray-500 hover:bg-gray-600 text-white rounded shadow-sm transition-colors"
                      >
                        Dismiss
                      </button>
                    </form>
                  )}
                </div>
              </div>
            ))}
          </div>
        )}
      </div>
    </div>
  );
}
