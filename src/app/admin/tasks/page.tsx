'use client';

import React, { useState, useEffect, useCallback, useTransition } from 'react';
import { getTasksAction, triggerBenchmarkAction, updateTaskStatusAction } from './actions';
import { logoutAdminAction } from '../login/actions';
import { AutomatedTask } from '@/lib/automation/benchmark';
import { sanitizeUrl } from '@/lib/sanitize';

export default function AdminTasksPage() {
  const [tasks, setTasks] = useState<AutomatedTask[]>([]);
  const [loading, setLoading] = useState<boolean>(true);
  const [filter, setFilter] = useState<string>('all');
  const [competitorFilter, setCompetitorFilter] = useState<string>('all');
  const [isPending, startTransition] = useTransition();
  const [triggering, setTriggering] = useState<boolean>(false);
  const [statusMessage, setStatusMessage] = useState<{ text: string; type: 'success' | 'error' } | null>(null);

  // Memoized task loader to comply with React strict lint rules and hook dependencies
  const loadTasks = useCallback(async () => {
    try {
      const fetchedTasks = await getTasksAction();
      setTasks(fetchedTasks);
    } catch (err) {
      console.error('Failed to load tasks', err);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    // Defer local loading/state updates if needed to prevent React cascading render issues
    const timer = setTimeout(() => {
      loadTasks();
    }, 0);
    return () => clearTimeout(timer);
  }, [loadTasks]);

  const handleLogout = () => {
    startTransition(async () => {
      await logoutAdminAction();
    });
  };

  const handleRunBenchmark = async () => {
    setTriggering(true);
    setStatusMessage(null);
    try {
      const res = await triggerBenchmarkAction();
      if (res.success) {
        setStatusMessage({
          text: `Benchmark completed! Added ${res.added} new tasks. Total tasks in storage: ${res.total}.`,
          type: 'success',
        });
        await loadTasks();
      } else {
        setStatusMessage({
          text: res.error || 'Failed to trigger benchmark due to server filesystem limits.',
          type: 'error',
        });
      }
    } catch (err) {
      setStatusMessage({
        text: (err as Error).message || 'Server error occurred while triggering.',
        type: 'error',
      });
    } finally {
      setTriggering(false);
    }
  };

  const handleStatusChange = async (taskId: string, newStatus: 'pending' | 'in_progress' | 'completed' | 'ignored') => {
    try {
      const res = await updateTaskStatusAction(taskId, newStatus);
      if (res.success) {
        await loadTasks();
      } else {
        alert(res.error || 'Failed to update task status.');
      }
    } catch (err) {
      alert((err as Error).message || 'Server error occurred while updating status.');
    }
  };

  const filteredTasks = tasks.filter((task) => {
    const matchesStatus = filter === 'all' || task.status === filter;
    const matchesCompetitor = competitorFilter === 'all' || task.sourceCompetitor === competitorFilter;
    return matchesStatus && matchesCompetitor;
  });

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10">
      <div className="flex flex-col md:flex-row md:items-center md:justify-between border-b border-gray-200 dark:border-gray-800 pb-6 mb-8">
        <div>
          <h1 className="text-3xl font-extrabold text-gray-900 dark:text-white">
            Automated Competitor Task Manager
          </h1>
          <p className="mt-2 text-sm text-gray-500 dark:text-gray-400">
            View, filter, and manage tasks generated by daily competitive US market benchmarking.
          </p>
        </div>
        <div className="mt-4 md:mt-0 flex flex-wrap gap-4">
          <button
            onClick={handleRunBenchmark}
            disabled={triggering}
            className="inline-flex items-center justify-center px-4 py-2 border border-transparent text-sm font-medium rounded-md text-white bg-primary hover:bg-blue-700 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-primary disabled:opacity-50 transition-colors"
          >
            {triggering ? 'Running Benchmark...' : 'Run Benchmark Now'}
          </button>
          <button
            onClick={handleLogout}
            disabled={isPending}
            className="inline-flex items-center justify-center px-4 py-2 border border-gray-300 dark:border-gray-600 text-sm font-medium rounded-md text-gray-700 dark:text-gray-200 bg-white dark:bg-gray-800 hover:bg-gray-50 dark:hover:bg-gray-700 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-primary transition-colors"
          >
            Logout
          </button>
        </div>
      </div>

      {statusMessage && (
        <div
          className={`p-4 rounded-md mb-6 ${
            statusMessage.type === 'success'
              ? 'bg-green-50 text-green-800 dark:bg-green-950/30 dark:text-green-300'
              : 'bg-red-50 text-red-800 dark:bg-red-950/30 dark:text-red-300'
          }`}
        >
          {statusMessage.text}
        </div>
      )}

      {/* Filters and Counters */}
      <div className="bg-white dark:bg-gray-800 shadow-sm rounded-lg border border-gray-200 dark:border-gray-700 p-6 mb-8">
        <div className="grid grid-cols-1 md:grid-cols-3 gap-6 items-center">
          <div>
            <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
              Filter by Competitor Status
            </label>
            <select
              value={filter}
              onChange={(e) => setFilter(e.target.value)}
              className="block w-full pl-3 pr-10 py-2 text-base border-gray-300 dark:border-gray-600 dark:bg-gray-700 dark:text-white rounded-md focus:outline-none focus:ring-primary focus:border-primary sm:text-sm"
            >
              <option value="all">All Statuses</option>
              <option value="pending">Pending</option>
              <option value="in_progress">In Progress</option>
              <option value="completed">Completed</option>
              <option value="ignored">Ignored</option>
            </select>
          </div>
          <div>
            <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
              Filter by Competitor
            </label>
            <select
              value={competitorFilter}
              onChange={(e) => setCompetitorFilter(e.target.value)}
              className="block w-full pl-3 pr-10 py-2 text-base border-gray-300 dark:border-gray-600 dark:bg-gray-700 dark:text-white rounded-md focus:outline-none focus:ring-primary focus:border-primary sm:text-sm"
            >
              <option value="all">All Competitors</option>
              <option value="Wirecutter">Wirecutter</option>
              <option value="RTINGS">RTINGS</option>
            </select>
          </div>
          <div className="text-right">
            <span className="inline-flex items-center px-3 py-1 rounded-full text-sm font-medium bg-blue-100 text-blue-800 dark:bg-blue-900/30 dark:text-blue-300">
              Total Found: {filteredTasks.length}
            </span>
          </div>
        </div>
      </div>

      {loading ? (
        <div className="text-center py-12 text-gray-500">Loading automated benchmarking tasks...</div>
      ) : filteredTasks.length === 0 ? (
        <div className="text-center py-12 bg-white dark:bg-gray-800 border border-gray-200 dark:border-gray-700 rounded-lg text-gray-500">
          No tasks found matching the filter criteria. Try clicking &quot;Run Benchmark Now&quot; to fetch competitor RSS feeds.
        </div>
      ) : (
        <div className="space-y-6">
          {filteredTasks.map((task) => (
            <div
              key={task.id}
              className="bg-white dark:bg-gray-800 shadow-sm border border-gray-200 dark:border-gray-700 rounded-lg p-6 flex flex-col md:flex-row justify-between gap-6"
            >
              <div className="flex-1 space-y-2">
                <div className="flex flex-wrap items-center gap-2">
                  <span
                    className={`inline-flex items-center px-2.5 py-0.5 rounded-full text-xs font-medium ${
                      task.sourceCompetitor === 'Wirecutter'
                        ? 'bg-emerald-100 text-emerald-800 dark:bg-emerald-950/30 dark:text-emerald-300'
                        : 'bg-purple-100 text-purple-800 dark:bg-purple-950/30 dark:text-purple-300'
                    }`}
                  >
                    {task.sourceCompetitor}
                  </span>
                  <span
                    className={`inline-flex items-center px-2.5 py-0.5 rounded-full text-xs font-medium ${
                      task.status === 'completed'
                        ? 'bg-green-100 text-green-800'
                        : task.status === 'in_progress'
                        ? 'bg-yellow-100 text-yellow-800'
                        : task.status === 'ignored'
                        ? 'bg-gray-100 text-gray-800'
                        : 'bg-blue-100 text-blue-800'
                    }`}
                  >
                    {task.status.replace('_', ' ')}
                  </span>
                </div>
                <h3 className="text-lg font-bold text-gray-900 dark:text-white">{task.title}</h3>
                <p className="text-sm text-gray-600 dark:text-gray-400 line-clamp-3">{task.description}</p>
                <div className="text-xs text-gray-400 mt-2">
                  Fetched on {new Date(task.createdAt).toLocaleString()} |{' '}
                  <a
                    href={sanitizeUrl(task.sourceUrl)}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="text-primary hover:underline"
                  >
                    View Original Competitor Source →
                  </a>
                </div>
              </div>

              <div className="flex items-center md:border-l md:border-gray-200 dark:md:border-gray-700 md:pl-6">
                <div>
                  <label className="block text-xs font-semibold uppercase tracking-wider text-gray-500 dark:text-gray-400 mb-2">
                    Modify Status
                  </label>
                  <select
                    value={task.status}
                    onChange={(e) =>
                      handleStatusChange(
                        task.id,
                        e.target.value as 'pending' | 'in_progress' | 'completed' | 'ignored'
                      )
                    }
                    className="block w-full pl-3 pr-10 py-1.5 text-sm border-gray-300 dark:border-gray-600 dark:bg-gray-700 dark:text-white rounded-md focus:outline-none focus:ring-primary focus:border-primary"
                  >
                    <option value="pending">Pending</option>
                    <option value="in_progress">In Progress</option>
                    <option value="completed">Completed</option>
                    <option value="ignored">Ignored</option>
                  </select>
                </div>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
