import fs from 'fs';
import path from 'path';
import { Task } from '@/types';
import Link from 'next/link';

async function getTasks(): Promise<Task[]> {
  const filePath = path.join(process.cwd(), 'src/lib/tasks.json');
  try {
    if (!fs.existsSync(filePath)) return [];
    const content = fs.readFileSync(filePath, 'utf-8');
    return JSON.parse(content);
  } catch (error) {
    console.error('Error reading tasks:', error);
    return [];
  }
}

export default async function AdminTasksPage() {
  const tasks = await getTasks();

  // Sort tasks by date (newest first)
  const sortedTasks = [...tasks].sort((a, b) =>
    new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()
  );

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-12">
      <div className="flex justify-between items-center mb-8">
        <div>
          <h1 className="text-3xl font-bold text-gray-900 dark:text-white">Content Strategy Tasks</h1>
          <p className="mt-2 text-gray-600 dark:text-gray-400">Automated tasks generated by competitor benchmarking.</p>
        </div>
        <div className="bg-blue-50 dark:bg-blue-900/30 px-4 py-2 rounded-lg border border-blue-100 dark:border-blue-800">
          <span className="text-blue-700 dark:text-blue-300 font-semibold">{tasks.length}</span>
          <span className="ml-2 text-blue-600 dark:text-blue-400 text-sm font-medium">Total Tasks</span>
        </div>
      </div>

      {sortedTasks.length === 0 ? (
        <div className="text-center py-20 bg-gray-50 dark:bg-gray-800/50 rounded-2xl border-2 border-dashed border-gray-200 dark:border-gray-700">
          <p className="text-gray-500 dark:text-gray-400 text-lg">No tasks found. Run a benchmark to generate tasks.</p>
        </div>
      ) : (
        <div className="bg-white dark:bg-gray-900 shadow overflow-hidden sm:rounded-md border border-gray-200 dark:border-gray-800">
          <ul className="divide-y divide-gray-200 dark:divide-gray-800">
            {sortedTasks.map((task) => (
              <li key={task.id}>
                <div className="px-4 py-6 sm:px-6 hover:bg-gray-50 dark:hover:bg-gray-800/50 transition-colors">
                  <div className="flex items-center justify-between">
                    <div className="flex items-center">
                      <p className="text-lg font-bold text-primary truncate">{task.title}</p>
                      <span className={`ml-3 px-2.5 py-0.5 rounded-full text-xs font-medium ${
                        task.priority === 'high' ? 'bg-red-100 text-red-800' :
                        task.priority === 'medium' ? 'bg-yellow-100 text-yellow-800' :
                        'bg-green-100 text-green-800'
                      }`}>
                        {task.priority}
                      </span>
                    </div>
                    <div className="ml-2 flex-shrink-0 flex">
                      <p className="px-2 inline-flex text-xs leading-5 font-semibold rounded-full bg-gray-100 text-gray-800 dark:bg-gray-800 dark:text-gray-300">
                        {task.type}
                      </p>
                    </div>
                  </div>
                  <div className="mt-2 sm:flex sm:justify-between">
                    <div className="sm:flex">
                      <p className="flex items-center text-sm text-gray-500 dark:text-gray-400">
                        {task.description}
                      </p>
                    </div>
                    <div className="mt-2 flex items-center text-sm text-gray-500 sm:mt-0 dark:text-gray-400">
                      <p>
                        Detected on <time dateTime={task.createdAt}>{new Date(task.createdAt).toLocaleDateString()}</time>
                      </p>
                    </div>
                  </div>
                  {task.sourceUrl && (
                    <div className="mt-4">
                      <Link
                        href={task.sourceUrl}
                        target="_blank"
                        className="text-sm font-medium text-blue-600 hover:text-blue-500 dark:text-blue-400 dark:hover:text-blue-300 flex items-center"
                      >
                        View competitor article
                        <svg className="ml-1 w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg">
                          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M10 6H6a2 2 0 00-2 2v10a2 2 0 002 2h10a2 2 0 002-2v-4M14 4h6m0 0v6m0-6L10 14" />
                        </svg>
                      </Link>
                    </div>
                  )}
                </div>
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}
