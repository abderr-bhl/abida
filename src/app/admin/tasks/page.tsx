'use client';

import { useState, useEffect, useCallback } from 'react';
import { Task, TaskStatus } from '@/types';
import { CheckCircle2, Clock, AlertCircle, ExternalLink, Archive } from 'lucide-react';

export default function AdminTasksPage() {
  const [tasks, setTasks] = useState<Task[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [token, setToken] = useState<string | null>(null);

  const fetchTasks = useCallback(async (authToken: string) => {
    try {
      const response = await fetch('/api/admin/tasks', {
        headers: {
          'Authorization': `Bearer ${authToken}`
        }
      });
      if (response.ok) {
        const data = await response.json();
        setTasks(data);
      } else {
        setError('Failed to fetch tasks. Please check your token.');
      }
    } catch (err) {
      setError('An error occurred while fetching tasks.');
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    // In a real app, this would come from a secure session or login
    const savedToken = localStorage.getItem('admin_token') || 'dev-token-123';

    // Defer initial state update and fetch to avoid hydration mismatch/cascading renders
    const timer = setTimeout(() => {
      setToken(savedToken);
      fetchTasks(savedToken);
    }, 0);

    return () => clearTimeout(timer);
  }, [fetchTasks]);

  const updateTaskStatus = async (id: string, status: TaskStatus) => {
    if (!token) return;

    try {
      const response = await fetch('/api/admin/tasks', {
        method: 'PATCH',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${token}`
        },
        body: JSON.stringify({ id, status })
      });

      if (response.ok) {
        setTasks(prev => prev.map(t => t.id === id ? { ...t, status, updatedAt: new Date().toISOString() } : t));
      }
    } catch (err) {
      console.error('Failed to update task', err);
    }
  };

  const getStatusIcon = (status: TaskStatus) => {
    switch (status) {
      case 'completed': return <CheckCircle2 className="w-5 h-5 text-green-500" />;
      case 'in-progress': return <Clock className="w-5 h-5 text-blue-500" />;
      case 'archived': return <Archive className="w-5 h-5 text-gray-400" />;
      default: return <AlertCircle className="w-5 h-5 text-amber-500" />;
    }
  };

  const sanitizeUrl = (url?: string) => {
    if (!url) return '#';
    try {
      const parsed = new URL(url);
      if (['http:', 'https:'].includes(parsed.protocol)) {
        return url;
      }
    } catch (e) {
      return '#';
    }
    return '#';
  };

  if (loading) return <div className="p-8 text-center">Loading automated tasks...</div>;

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-12">
      <div className="flex justify-between items-center mb-8">
        <div>
          <h1 className="text-3xl font-bold text-gray-900 dark:text-white">Automated Task Dashboard</h1>
          <p className="mt-2 text-gray-600 dark:text-gray-400">Manage tasks generated by daily competitive benchmarking.</p>
        </div>
        <div className="text-sm text-gray-500 bg-gray-100 px-3 py-1 rounded-full dark:bg-gray-800">
          {tasks.length} tasks identified
        </div>
      </div>

      {error && (
        <div className="bg-red-50 border-l-4 border-red-400 p-4 mb-8">
          <p className="text-red-700">{error}</p>
        </div>
      )}

      <div className="bg-white shadow overflow-hidden sm:rounded-md dark:bg-gray-900 border border-gray-200 dark:border-gray-800">
        <ul className="divide-y divide-gray-200 dark:divide-gray-800">
          {tasks.length === 0 ? (
            <li className="p-8 text-center text-gray-500">No tasks found. Run a benchmark to generate tasks.</li>
          ) : (
            tasks.map((task) => (
              <li key={task.id} className="p-6 hover:bg-gray-50 dark:hover:bg-gray-800/50 transition-colors">
                <div className="flex items-center justify-between">
                  <div className="flex-1 min-w-0">
                    <div className="flex items-center space-x-3">
                      {getStatusIcon(task.status)}
                      <h2 className="text-lg font-semibold text-gray-900 dark:text-white truncate">{task.title}</h2>
                      <span className={`inline-flex items-center px-2.5 py-0.5 rounded-full text-xs font-medium ${
                        task.priority === 'high' ? 'bg-red-100 text-red-800' :
                        task.priority === 'medium' ? 'bg-yellow-100 text-yellow-800' : 'bg-blue-100 text-blue-800'
                      }`}>
                        {task.priority}
                      </span>
                    </div>
                    <p className="mt-1 text-sm text-gray-600 dark:text-gray-400">{task.description}</p>
                    <div className="mt-2 flex items-center space-x-4 text-xs text-gray-500">
                      <span>Source: <span className="font-medium text-gray-700 dark:text-gray-300">{task.competitor}</span></span>
                      <span>Created: {new Date(task.createdAt).toLocaleDateString()}</span>
                      {task.sourceUrl && (
                        <a
                          href={sanitizeUrl(task.sourceUrl)}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="flex items-center text-primary hover:underline"
                        >
                          View Competitor <ExternalLink className="w-3 h-3 ml-1" />
                        </a>
                      )}
                    </div>
                  </div>
                  <div className="ml-6 flex items-center space-x-2">
                    <select
                      value={task.status}
                      onChange={(e) => updateTaskStatus(task.id, e.target.value as TaskStatus)}
                      className="block w-full pl-3 pr-10 py-2 text-sm border-gray-300 focus:outline-none focus:ring-primary focus:border-primary rounded-md dark:bg-gray-800 dark:border-gray-700 dark:text-white"
                    >
                      <option value="pending">Pending</option>
                      <option value="in-progress">In Progress</option>
                      <option value="completed">Completed</option>
                      <option value="archived">Archived</option>
                    </select>
                  </div>
                </div>
              </li>
            ))
          )}
        </ul>
      </div>
    </div>
  );
}
