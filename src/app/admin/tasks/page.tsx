'use client';

import { Task } from '@/types';
import { useState, useEffect, useCallback } from 'react';

export default function AdminTasksPage() {
  const [tasks, setTasks] = useState<Task[]>([]);
  const [loading, setLoading] = useState(true);
  const [authenticated, setAuthenticated] = useState(false);
  const [token, setToken] = useState('');

  const fetchTasks = useCallback(async () => {
    try {
      const res = await fetch('/api/admin/tasks/list');
      if (res.ok) {
        const data = await res.json();
        setTasks(data);
      }
    } catch (error) {
      console.error('Failed to fetch tasks:', error);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    const savedToken = localStorage.getItem('admin_token');
    if (savedToken) {
      // Use setTimeout to defer state updates and avoid "cascading renders" lint error
      const timer = setTimeout(() => {
        setToken(savedToken);
        setAuthenticated(true);
      }, 0);
      return () => clearTimeout(timer);
    } else {
      const timer = setTimeout(() => {
        setLoading(false);
      }, 0);
      return () => clearTimeout(timer);
    }
  }, []);

  useEffect(() => {
    if (authenticated) {
      const timer = setTimeout(() => {
        fetchTasks();
      }, 0);
      return () => clearTimeout(timer);
    }
  }, [authenticated, fetchTasks]);

  const handleLogin = (e: React.FormEvent) => {
    e.preventDefault();
    if (token) {
      localStorage.setItem('admin_token', token);
      setAuthenticated(true);
      setLoading(true);
    }
  };

  const markAsDone = async (id: string) => {
    try {
      const res = await fetch('/api/admin/tasks', {
        method: 'PATCH',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ id, status: 'completed' }),
      });
      if (res.ok) {
        setTasks(prev => prev.map(t => t.id === id ? { ...t, status: 'completed' } : t));
      }
    } catch (error) {
      console.error('Failed to update task:', error);
    }
  };

  if (loading) return <div className="p-8 text-center">Loading tasks...</div>;

  if (!authenticated) {
    return (
      <div className="max-w-md mx-auto mt-20 p-8 bg-white rounded-lg shadow dark:bg-gray-900 border border-gray-200 dark:border-gray-800">
        <h1 className="text-2xl font-bold mb-6 text-gray-900 dark:text-white">Admin Login</h1>
        <form onSubmit={handleLogin} className="space-y-4">
          <div>
            <label className="block text-sm font-medium text-gray-700 dark:text-gray-300">Admin Token</label>
            <input
              type="password"
              value={token}
              onChange={(e) => setToken(e.target.value)}
              className="mt-1 block w-full border border-gray-300 rounded-md shadow-sm p-2 dark:bg-gray-800 dark:border-gray-700 dark:text-white"
              required
            />
          </div>
          <button type="submit" className="w-full bg-primary text-white p-2 rounded-md font-medium hover:bg-blue-700">
            Login
          </button>
        </form>
      </div>
    );
  }

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-12">
      <div className="flex justify-between items-center mb-8">
        <div>
          <h1 className="text-3xl font-bold text-gray-900 dark:text-white">Admin Task Dashboard</h1>
          <p className="mt-2 text-gray-600 dark:text-gray-400">
            Tasks generated by automated competitive benchmarking.
          </p>
        </div>
      </div>

      {tasks.length === 0 ? (
        <div className="bg-white p-8 rounded-lg shadow text-center dark:bg-gray-900">
          <p className="text-gray-500">No tasks generated yet. The benchmarking system will create tasks as it finds new competitor content.</p>
        </div>
      ) : (
        <div className="grid gap-6">
          {tasks.map((task) => (
            <div key={task.id} className="bg-white p-6 rounded-lg shadow-sm border border-gray-200 dark:bg-gray-900 dark:border-gray-800">
              <div className="flex justify-between items-start">
                <div className="flex-1">
                  <div className="flex items-center gap-3">
                    <h3 className="text-xl font-bold text-gray-900 dark:text-white">{task.title}</h3>
                    <span className={`px-2 py-1 text-xs font-semibold rounded-full uppercase ${
                      task.priority === 'high' ? 'bg-red-100 text-red-800' :
                      task.priority === 'medium' ? 'bg-yellow-100 text-yellow-800' :
                      'bg-green-100 text-green-800'
                    }`}>
                      {task.priority}
                    </span>
                    <span className={`px-2 py-1 text-xs font-semibold rounded-full uppercase ${
                      task.status === 'completed' ? 'bg-green-100 text-green-800' : 'bg-blue-100 text-blue-800'
                    }`}>
                      {task.status}
                    </span>
                  </div>
                  <p className="mt-2 text-gray-600 dark:text-gray-400">{task.description}</p>
                  <div className="mt-4 flex items-center gap-4">
                    <a
                      href={task.sourceUrl}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="text-primary hover:underline text-sm font-medium"
                    >
                      View Source Article →
                    </a>
                    <span className="text-gray-400 text-sm">Created: {new Date(task.createdAt).toLocaleDateString()}</span>
                  </div>
                </div>
                <div className="ml-6">
                  {task.status !== 'completed' && (
                    <button
                      onClick={() => markAsDone(task.id)}
                      className="bg-primary text-white px-4 py-2 rounded-md text-sm font-medium hover:bg-blue-700 transition-colors"
                    >
                      Mark as Done
                    </button>
                  )}
                </div>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
