import { getTasks } from '@/lib/automation/benchmark';
import { runBenchmark, updateTaskStatus } from './actions';
import { logout } from '../login/actions';
import { ExternalLink, CheckCircle, Clock, Play, LogOut } from 'lucide-react';
import { cn } from '@/lib/utils';

export default async function TasksPage() {
  const tasks = await getTasks();

  return (
    <div className="max-w-7xl mx-auto py-10 px-4 sm:px-6 lg:px-8">
      <div className="flex justify-between items-center mb-8">
        <div>
          <h1 className="text-3xl font-bold text-gray-900">Automated Content Tasks</h1>
          <p className="mt-2 text-sm text-gray-600">
            Monitor and manage tasks generated by the competitive benchmarking system.
          </p>
        </div>
        <div className="flex gap-4">
          <form action={runBenchmark}>
            <button
              type="submit"
              className="inline-flex items-center px-4 py-2 border border-transparent text-sm font-medium rounded-md shadow-sm text-white bg-primary hover:bg-blue-700 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-primary"
            >
              <Play className="mr-2 h-4 w-4" />
              Run Benchmark Now
            </button>
          </form>
          <form action={logout}>
            <button
              type="submit"
              className="inline-flex items-center px-4 py-2 border border-gray-300 text-sm font-medium rounded-md shadow-sm text-gray-700 bg-white hover:bg-gray-50 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-primary"
            >
              <LogOut className="mr-2 h-4 w-4" />
              Logout
            </button>
          </form>
        </div>
      </div>

      <div className="bg-white shadow overflow-hidden sm:rounded-md">
        <ul className="divide-y divide-gray-200">
          {tasks.length === 0 ? (
            <li className="px-6 py-12 text-center text-gray-500">
              No tasks found. Run a benchmark to discover new content opportunities.
            </li>
          ) : (
            tasks.map((task) => (
              <li key={task.id}>
                <div className="px-6 py-4 flex items-center justify-between">
                  <div className="flex-1 min-w-0">
                    <div className="flex items-center justify-between">
                      <p className="text-sm font-medium text-primary truncate">{task.competitor}</p>
                      <div className="ml-2 flex-shrink-0 flex">
                        <p
                          className={cn(
                            "px-2 inline-flex text-xs leading-5 font-semibold rounded-full",
                            task.status === 'completed' ? "bg-green-100 text-green-800" :
                            task.status === 'in-progress' ? "bg-yellow-100 text-yellow-800" :
                            "bg-gray-100 text-gray-800"
                          )}
                        >
                          {task.status}
                        </p>
                      </div>
                    </div>
                    <div className="mt-2">
                      <h3 className="text-lg font-semibold text-gray-900">{task.title}</h3>
                      <p className="mt-1 text-sm text-gray-600 line-clamp-2">{task.description}</p>
                    </div>
                    <div className="mt-2 flex items-center text-sm text-gray-500">
                      <Clock className="flex-shrink-0 mr-1.5 h-4 w-4" />
                      <span>Added on {new Date(task.createdAt).toLocaleDateString()}</span>
                      <span className="mx-2">&bull;</span>
                      <a
                        href={task.sourceUrl}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="inline-flex items-center text-blue-600 hover:underline"
                        aria-label={`View source article for ${task.title} (opens in a new tab)`}
                      >
                        Source <ExternalLink className="ml-1 h-3 w-3" />
                      </a>
                    </div>
                  </div>
                  <div className="ml-6 flex-shrink-0 flex gap-2">
                    {task.status !== 'completed' && (
                      <form action={updateTaskStatus.bind(null, task.id, 'completed')}>
                        <button
                          type="submit"
                          className="inline-flex items-center p-2 border border-transparent rounded-full shadow-sm text-white bg-green-600 hover:bg-green-700 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-green-500"
                          title="Mark as Completed"
                        >
                          <CheckCircle className="h-5 w-5" />
                        </button>
                      </form>
                    )}
                  </div>
                </div>
              </li>
            ))
          )}
        </ul>
      </div>
    </div>
  );
}
