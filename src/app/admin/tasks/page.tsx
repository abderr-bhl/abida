import { getTasks } from '@/lib/automation/benchmark';
import { triggerBenchmark, updateStatusAction, logoutAction } from './actions';
import { sanitizeUrl } from '@/lib/sanitize';

export const dynamic = 'force-dynamic';

export default async function AdminTasksPage() {
  const tasks = getTasks();

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10">
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between mb-8 pb-4 border-b border-gray-200 gap-4">
        <div>
          <h1 className="text-3xl font-bold text-gray-900">Automated Benchmarking Tasks</h1>
          <p className="mt-1 text-sm text-gray-600">
            Tasks generated by daily competitor benchmarks (Wirecutter, RTINGS).
          </p>
        </div>
        <div className="flex items-center gap-3">
          <form action={triggerBenchmark}>
            <button
              type="submit"
              className="inline-flex items-center px-4 py-2 border border-transparent text-sm font-medium rounded-md shadow-sm text-white bg-blue-600 hover:bg-blue-700 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-blue-500"
            >
              Run Benchmark Now
            </button>
          </form>
          <form action={logoutAction}>
            <button
              type="submit"
              className="inline-flex items-center px-4 py-2 border border-gray-300 text-sm font-medium rounded-md text-gray-700 bg-white hover:bg-gray-50 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-blue-500"
            >
              Logout
            </button>
          </form>
        </div>
      </div>

      {tasks.length === 0 ? (
        <div className="bg-white p-8 text-center rounded-lg border border-gray-200 shadow-sm">
          <p className="text-gray-500">No benchmark tasks found yet. Click &quot;Run Benchmark Now&quot; to fetch recent competitor content.</p>
        </div>
      ) : (
        <div className="bg-white shadow-sm overflow-hidden border border-gray-200 sm:rounded-lg">
          <ul className="divide-y divide-gray-200">
            {tasks.map((task) => (
              <li key={task.id} className="p-6 hover:bg-gray-50 transition">
                <div className="flex flex-col md:flex-row md:items-center md:justify-between gap-4">
                  <div className="flex-1">
                    <div className="flex items-center gap-2 mb-1">
                      <span className="inline-flex items-center px-2.5 py-0.5 rounded-full text-xs font-medium bg-blue-100 text-blue-800">
                        {task.competitor}
                      </span>
                      <span className={`inline-flex items-center px-2.5 py-0.5 rounded-full text-xs font-medium ${
                        task.status === 'completed'
                          ? 'bg-green-100 text-green-800'
                          : task.status === 'in_progress'
                          ? 'bg-yellow-100 text-yellow-800'
                          : 'bg-gray-100 text-gray-800'
                      }`}>
                        {task.status.replace('_', ' ')}
                      </span>
                      <span className="text-xs text-gray-400">
                        {new Date(task.createdAt).toLocaleDateString()}
                      </span>
                    </div>
                    <h2 className="text-lg font-semibold text-gray-900">{task.title}</h2>
                    <p className="mt-1 text-sm text-gray-600">{task.description}</p>
                    <div className="mt-2">
                      <a
                        href={sanitizeUrl(task.sourceUrl)}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="text-xs text-blue-600 hover:text-blue-800 underline inline-flex items-center gap-1"
                      >
                        View Source Article &rarr;
                      </a>
                    </div>
                  </div>

                  <div className="flex items-center gap-2">
                    {task.status !== 'pending' && (
                      <form action={updateStatusAction.bind(null, task.id, 'pending')}>
                        <button
                          type="submit"
                          className="px-3 py-1.5 text-xs font-medium text-gray-700 bg-gray-100 rounded hover:bg-gray-200"
                        >
                          Mark Pending
                        </button>
                      </form>
                    )}
                    {task.status !== 'in_progress' && (
                      <form action={updateStatusAction.bind(null, task.id, 'in_progress')}>
                        <button
                          type="submit"
                          className="px-3 py-1.5 text-xs font-medium text-yellow-800 bg-yellow-100 rounded hover:bg-yellow-200"
                        >
                          Mark In Progress
                        </button>
                      </form>
                    )}
                    {task.status !== 'completed' && (
                      <form action={updateStatusAction.bind(null, task.id, 'completed')}>
                        <button
                          type="submit"
                          className="px-3 py-1.5 text-xs font-medium text-green-800 bg-green-100 rounded hover:bg-green-200"
                        >
                          Mark Completed
                        </button>
                      </form>
                    )}
                  </div>
                </div>
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}
