'use client';

import { useState, useTransition } from 'react';
import { BenchmarkTask } from '@/types';
import { triggerBenchmarkAction, updateTaskStatusAction } from './actions';
import { sanitizeUrl } from '@/lib/sanitize';
import {
  Play,
  ExternalLink,
  CheckCircle2,
  Clock,
  XCircle,
  AlertCircle,
  RefreshCw,
} from 'lucide-react';

interface TaskListProps {
  initialTasks: BenchmarkTask[];
}

export default function TaskList({ initialTasks }: TaskListProps) {
  const [tasks, setTasks] = useState<BenchmarkTask[]>(initialTasks);
  const [filter, setFilter] = useState<string>('all');
  const [isPending, startTransition] = useTransition();
  const [message, setMessage] = useState<string | null>(null);

  const filteredTasks = tasks.filter((t) => {
    if (filter === 'all') return true;
    return t.status === filter;
  });

  const handleRunBenchmark = () => {
    setMessage(null);
    startTransition(async () => {
      const res = await triggerBenchmarkAction();
      if (res.success) {
        setMessage(`Benchmark run completed! Found ${res.count} new task(s).`);
        window.location.reload();
      }
    });
  };

  const handleStatusChange = (taskId: string, newStatus: BenchmarkTask['status']) => {
    startTransition(async () => {
      const res = await updateTaskStatusAction(taskId, newStatus);
      if (res.success) {
        setTasks((prev) =>
          prev.map((t) => (t.id === taskId ? { ...t, status: newStatus } : t))
        );
      }
    });
  };

  const getStatusBadge = (status: BenchmarkTask['status']) => {
    switch (status) {
      case 'completed':
        return (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-medium bg-green-100 text-green-800 dark:bg-green-900/40 dark:text-green-300">
            <CheckCircle2 className="w-3 h-3" /> Completed
          </span>
        );
      case 'in_progress':
        return (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-medium bg-blue-100 text-blue-800 dark:bg-blue-900/40 dark:text-blue-300">
            <Clock className="w-3 h-3" /> In Progress
          </span>
        );
      case 'dismissed':
        return (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-medium bg-gray-100 text-gray-800 dark:bg-gray-800 dark:text-gray-300">
            <XCircle className="w-3 h-3" /> Dismissed
          </span>
        );
      default:
        return (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-medium bg-amber-100 text-amber-800 dark:bg-amber-900/40 dark:text-amber-300">
            <AlertCircle className="w-3 h-3" /> Pending
          </span>
        );
    }
  };

  return (
    <div className="space-y-6">
      {/* Top Bar with Trigger Action and Filter */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 bg-white dark:bg-gray-800 p-6 rounded-xl border border-gray-200 dark:border-gray-700 shadow-sm">
        <div>
          <h2 className="text-lg font-semibold text-gray-900 dark:text-white">
            Automated Competitive Tasks
          </h2>
          <p className="text-sm text-gray-500 dark:text-gray-400">
            Daily tasks generated by comparing competitor RSS feeds (Wirecutter, RTINGS)
          </p>
        </div>

        <button
          onClick={handleRunBenchmark}
          disabled={isPending}
          className="flex items-center gap-2 px-4 py-2 bg-blue-600 hover:bg-blue-700 text-white font-medium text-sm rounded-lg shadow-sm focus:outline-none focus:ring-2 focus:ring-blue-500 disabled:opacity-50 transition-colors shrink-0"
        >
          {isPending ? (
            <RefreshCw className="w-4 h-4 animate-spin" />
          ) : (
            <Play className="w-4 h-4" />
          )}
          Run Benchmark Now
        </button>
      </div>

      {message && (
        <div className="p-4 bg-blue-50 dark:bg-blue-900/30 border border-blue-200 dark:border-blue-800 text-blue-700 dark:text-blue-300 rounded-lg text-sm">
          {message}
        </div>
      )}

      {/* Filters & Counter */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
        <div className="flex flex-wrap gap-2">
          {['all', 'pending', 'in_progress', 'completed', 'dismissed'].map((f) => (
            <button
              key={f}
              onClick={() => setFilter(f)}
              className={`px-3 py-1.5 text-xs font-medium rounded-lg capitalize transition-colors ${
                filter === f
                  ? 'bg-blue-600 text-white'
                  : 'bg-white dark:bg-gray-800 text-gray-600 dark:text-gray-300 border border-gray-200 dark:border-gray-700 hover:bg-gray-50 dark:hover:bg-gray-700'
              }`}
            >
              {f.replace('_', ' ')}
            </button>
          ))}
        </div>

        <span className="text-xs text-gray-500 dark:text-gray-400">
          Showing {filteredTasks.length} of {tasks.length} tasks
        </span>
      </div>

      {/* Task List Table / Cards */}
      {filteredTasks.length === 0 ? (
        <div className="bg-white dark:bg-gray-800 border border-gray-200 dark:border-gray-700 rounded-xl p-12 text-center">
          <p className="text-gray-500 dark:text-gray-400">No tasks found for this filter.</p>
        </div>
      ) : (
        <div className="space-y-4">
          {filteredTasks.map((task) => (
            <div
              key={task.id}
              className="bg-white dark:bg-gray-800 border border-gray-200 dark:border-gray-700 rounded-xl p-6 shadow-sm flex flex-col md:flex-row items-start md:items-center justify-between gap-4 transition-all hover:border-gray-300 dark:hover:border-gray-600"
            >
              <div className="space-y-2 max-w-3xl">
                <div className="flex flex-wrap items-center gap-2">
                  {getStatusBadge(task.status)}
                  <span className="px-2 py-0.5 rounded text-xs font-semibold bg-gray-100 text-gray-700 dark:bg-gray-700 dark:text-gray-300">
                    {task.source}
                  </span>
                  <span className="text-xs text-gray-400">
                    {new Date(task.createdAt).toLocaleDateString('en-US', {
                      month: 'short',
                      day: 'numeric',
                      year: 'numeric',
                    })}
                  </span>
                </div>

                <h3 className="text-base font-semibold text-gray-900 dark:text-white">
                  {task.title}
                </h3>

                <p className="text-sm text-gray-600 dark:text-gray-300 leading-relaxed">
                  {task.description}
                </p>

                {task.url && (
                  <a
                    href={sanitizeUrl(task.url)}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="inline-flex items-center gap-1 text-xs text-blue-600 dark:text-blue-400 hover:underline pt-1"
                  >
                    View Original Competitor Source <ExternalLink className="w-3 h-3" />
                  </a>
                )}
              </div>

              <div className="flex flex-wrap items-center gap-2 shrink-0 self-end md:self-center">
                {task.status !== 'in_progress' && (
                  <button
                    onClick={() => handleStatusChange(task.id, 'in_progress')}
                    disabled={isPending}
                    className="px-3 py-1.5 text-xs font-medium text-blue-700 dark:text-blue-300 bg-blue-50 dark:bg-blue-900/30 hover:bg-blue-100 rounded-lg transition-colors"
                  >
                    Mark In Progress
                  </button>
                )}
                {task.status !== 'completed' && (
                  <button
                    onClick={() => handleStatusChange(task.id, 'completed')}
                    disabled={isPending}
                    className="px-3 py-1.5 text-xs font-medium text-green-700 dark:text-green-300 bg-green-50 dark:bg-green-900/30 hover:bg-green-100 rounded-lg transition-colors"
                  >
                    Mark Completed
                  </button>
                )}
                {task.status !== 'dismissed' && (
                  <button
                    onClick={() => handleStatusChange(task.id, 'dismissed')}
                    disabled={isPending}
                    className="px-3 py-1.5 text-xs font-medium text-gray-600 dark:text-gray-400 bg-gray-100 dark:bg-gray-700 hover:bg-gray-200 rounded-lg transition-colors"
                  >
                    Dismiss
                  </button>
                )}
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
